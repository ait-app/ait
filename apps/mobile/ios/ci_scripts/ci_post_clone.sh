#!/bin/sh
set -eu

# Xcode Cloud invokes this hook from ios/ci_scripts, not the monorepo root.
if [ -z "${CI_PRIMARY_REPOSITORY_PATH:-}" ]; then
  echo "error: CI_PRIMARY_REPOSITORY_PATH is required; run this hook in Xcode Cloud." >&2
  exit 1
fi

cd "$CI_PRIMARY_REPOSITORY_PATH"
repo_root="$(pwd -P)"
ios_dir="$repo_root/apps/mobile/ios"

for file in \
  "$repo_root/package-lock.json" \
  "$ios_dir/Podfile.lock" \
  "$ios_dir/Ait.xcodeproj/project.pbxproj" \
  "$ios_dir/Ait.xcworkspace/contents.xcworkspacedata" \
  "$ios_dir/Ait.xcodeproj/xcshareddata/xcschemes/Ait.xcscheme"; do
  if [ ! -f "$file" ]; then
    echo "error: Missing $file. Commit the iOS project, shared scheme, workspace and lockfiles." >&2
    exit 1
  fi
done

export CI=1
export HOMEBREW_NO_AUTO_UPDATE=1
export HOMEBREW_NO_INSTALL_CLEANUP=1
export EXPO_NO_TELEMETRY=1
export ELECTRON_SKIP_BINARY_DOWNLOAD=1
export PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD=1
export APP_VARIANT="${APP_VARIANT:-production}"
export IOS_BUNDLE_IDENTIFIER="${IOS_BUNDLE_IDENTIFIER:-com.necokeine.ait}"
export APPLE_TEAM_ID="${APPLE_TEAM_ID:-SVS7GV79T9}"
export EXTRA_PACKAGER_ARGS="${EXTRA_PACKAGER_ARGS:---max-workers 2}"
unset AIT_WEB_PLATFORM

echo "[Ait] Preparing Node.js 22 and CocoaPods"
if ! brew list --versions node@22 >/dev/null 2>&1; then
  brew install node@22
fi
export PATH="$(brew --prefix node@22)/bin:$(brew --prefix)/bin:$PATH"
if ! command -v pod >/dev/null 2>&1; then
  brew install cocoapods
fi
node --version
npm --version
pod --version

echo "[Ait] Installing locked workspace dependencies"
npm ci --include=dev --no-audit --no-fund

# Native files are committed. A new app version must update them before CI.
node <<'NODE'
const { execFileSync } = require('node:child_process');
const { getNativeReleaseVersion } = require('./apps/mobile/native-release-version.js');
const expected = getNativeReleaseVersion(require('./apps/mobile/package.json').version).appVersion;
const actual = execFileSync('/usr/libexec/PlistBuddy', [
  '-c', 'Print :CFBundleShortVersionString', 'apps/mobile/ios/Ait/Info.plist',
], { encoding: 'utf8' }).trim();
if (actual !== expected) {
  throw new Error(`iOS version ${actual} differs from package version ${expected}. Run Expo prebuild locally with the release identity and commit the updated iOS project.`);
}
NODE

echo "[Ait] Building shared packages and the Terminal WebView"
npm run build:ui-deps
npm run build:terminal-webview --workspace=@ait/mobile

echo "[Ait] Installing locked CocoaPods dependencies"
cd "$ios_dir"
pod install --deployment

# Hooks and Xcode build phases run in separate shells. Persist the Node path
# and app configuration for React Native's build scripts on this build machine.
# CocoaPods may create this file too, so write it after pod install.
node <<'NODE'
const fs = require('node:fs');
const path = require('node:path');
const quote = (value) => "'" + value.replaceAll("'", "'\\''") + "'";
const lines = [
  '# Generated by ci_post_clone.sh for this Xcode Cloud build. Do not commit.',
  `export NODE_BINARY=${quote(process.execPath)}`,
  `export PATH=${quote(path.dirname(process.execPath))}:"$PATH"`,
  'unset AIT_WEB_PLATFORM',
];
for (const name of [
  'APP_VARIANT', 'IOS_BUNDLE_IDENTIFIER', 'APPLE_TEAM_ID',
  'EXPO_NO_TELEMETRY', 'EXTRA_PACKAGER_ARGS',
]) {
  lines.push(`export ${name}=${quote(process.env[name])}`);
}
fs.writeFileSync('.xcode.env.local', lines.join('\n') + '\n');
NODE

echo "[Ait] Dependencies are ready for the Xcode Cloud archive action"
