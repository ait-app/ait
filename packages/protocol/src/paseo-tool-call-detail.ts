export function buildPaseoToolDetailSections(
  toolName: string,
  input: unknown,
  output: unknown,
): PaseoToolDetailSection[] | null {
  const leafName = getAitToolLeafName(toolName);
  if (!leafName) return null;

  return buildDetailSectionsFromSpec(TOOL_SPECS[leafName] ?? {}, input, output);
}
