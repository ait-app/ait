import { access, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const syncNative = process.argv.includes("--sync-native");
const brand = JSON.parse(await readFile(resolve(root, "assets/brand/ait-mark.json")));
const { colors, darkColors, placements } = brand;
const outputs = new Map();

function svg(body, viewBox = "0 0 1024 1024", size = 1024) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="${viewBox}" role="img" aria-label="AIT"><!-- Generated by scripts/generate-brand-assets.mjs. -->${body}</svg>\n`;
}

function bird(transform = placements.icon, monochrome, small = false, palette = colors) {
  const paths = monochrome
    ? `<path d="${small ? brand.smallSilhouette : brand.silhouette}" fill="${monochrome}"/>`
    : brand.faces
        .map((d, i) => `<path d="${d}" fill="${i === 0 ? palette.primary : palette.secondary}"/>`)
        .join("");
  return `<g transform="${transform}">${paths}</g>`;
}

function iconTile(palette) {
  return svg(
    `<rect x="48" y="48" width="928" height="928" rx="208" fill="${palette.canvas}" stroke="${palette.border}" stroke-width="2"/>${bird(placements.icon, undefined, false, palette)}`,
  );
}

const tile = iconTile(colors);
// Full bleed, opaque square: the launcher supplies its own mask.
const mobile = svg(`<rect width="1024" height="1024" fill="${colors.canvas}"/>${bird()}`);
const maskable = svg(
  `<rect width="1024" height="1024" fill="${colors.canvas}"/>${bird(placements.maskable)}`,
);
// Both Android's adaptive safe circle and the PWA maskable safe circle retain every tip.
const adaptive = svg(bird(placements.adaptive));
function stackedLockup(palette) {
  return svg(
    `${bird(placements.stackedMark, undefined, false, palette)}<path d="${brand.wordmark}" transform="${placements.stackedWordmark}" fill="${palette.ink}"/>`,
  );
}

const splash = stackedLockup(colors);
const splashDark = stackedLockup(darkColors);

async function png(source, size, opaque = false) {
  let pipeline = sharp(Buffer.from(source)).resize(size, size);
  if (opaque) pipeline = pipeline.flatten({ background: colors.canvas }).removeAlpha();
  return pipeline.png({ compressionLevel: 9 }).toBuffer();
}

function add(path, contents) {
  outputs.set(path, Buffer.isBuffer(contents) ? contents : Buffer.from(contents));
}

// PNG-backed ICO entries are supported by the Windows versions supported by Electron.
async function ico() {
  const sizes = [16, 24, 32, 48, 64, 128, 256];
  const images = await Promise.all(
    sizes.map((size) => png(size <= 32 ? favicon("light") : tile, size)),
  );
  const header = Buffer.alloc(6 + sizes.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(sizes.length, 4);
  let offset = header.length;
  sizes.forEach((size, i) => {
    const entry = 6 + i * 16;
    header[entry] = size === 256 ? 0 : size;
    header[entry + 1] = size === 256 ? 0 : size;
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(images[i].length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += images[i].length;
  });
  return Buffer.concat([header, ...images]);
}

async function icns() {
  const entries = [
    ["icp4", 16],
    ["icp5", 32],
    ["icp6", 64],
    ["ic07", 128],
    ["ic08", 256],
    ["ic09", 512],
    ["ic10", 1024],
    ["ic11", 32],
    ["ic12", 64],
    ["ic13", 256],
    ["ic14", 512],
  ];
  const chunks = await Promise.all(
    entries.map(async ([type, size]) => {
      const image = await png(size <= 32 ? favicon("light") : tile, size);
      const header = Buffer.alloc(8);
      header.write(type, 0, 4, "ascii");
      header.writeUInt32BE(image.length + 8, 4);
      return Buffer.concat([header, image]);
    }),
  );
  const header = Buffer.alloc(8);
  header.write("icns");
  header.writeUInt32BE(8 + chunks.reduce((sum, chunk) => sum + chunk.length, 0), 4);
  return Buffer.concat([header, ...chunks]);
}

function favicon(scheme, status = "idle") {
  const palette = scheme === "dark" ? darkColors : colors;
  const badge =
    status === "idle"
      ? ""
      : `<circle cx="26" cy="26" r="5" fill="${status === "running" ? "#3B82F6" : "#22C55E"}" stroke="${palette.canvas}" stroke-width="1.5"/>`;
  return svg(
    `${bird("translate(1 5) scale(0.04545)", palette.primary, true)}${badge}`,
    "0 0 32 32",
    48,
  );
}

for (const scheme of ["light", "dark"]) {
  const palette = scheme === "dark" ? darkColors : colors;
  const suffix = scheme === "dark" ? "-dark" : "";
  add(`assets/brand/logo${suffix}.svg`, iconTile(palette));
  add(`assets/brand/logo${suffix}.png`, await png(iconTile(palette), 512));
  add(
    `assets/brand/ait-mark${suffix}.svg`,
    svg(bird("", undefined, false, palette), brand.viewBox, 660).replace(
      'height="660"',
      'height="464"',
    ),
  );
  add(
    `assets/brand/ait-mark-mono${suffix}.svg`,
    svg(bird("", palette.ink), brand.viewBox, 660).replace('height="660"', 'height="464"'),
  );
  add(`assets/brand/ait-mark-small${suffix}.svg`, favicon(scheme));
  add(`assets/brand/ait-lockup-stacked${suffix}.svg`, stackedLockup(palette));
  add(
    `assets/brand/ait-lockup-horizontal${suffix}.svg`,
    svg(
      `${bird("translate(48 48) scale(0.5)", undefined, false, palette)}<path d="${brand.wordmark}" transform="translate(440 116)" fill="${palette.ink}"/>`,
      "0 0 870 328",
      870,
    ).replace('height="870"', 'height="328"'),
  );
}

for (const [filename, size] of Object.entries({
  "icon.png": 1024,
  "icon-dev.png": 1024,
  "32x32.png": 32,
  "64x64.png": 64,
  "128x128.png": 128,
  "128x128@2x.png": 256,
  "256x256.png": 256,
  "512x512.png": 512,
}))
  add(`apps/desktop/assets/${filename}`, await png(size <= 32 ? favicon("light") : tile, size));
add("apps/desktop/assets/icon.ico", await ico());
add("apps/desktop/assets/icon.icns", await icns());

const images = "apps/mobile/assets/images";
add(`${images}/icon.png`, await png(mobile, 1024, true));
add(`${images}/android-icon-foreground.png`, await png(adaptive, 1024));
add(`${images}/notification-icon.png`, await png(svg(bird(placements.icon, colors.surface)), 96));
add(`${images}/splash-icon.png`, await png(splash, 1024));
add(`${images}/splash-icon-dark.png`, await png(splashDark, 1024));
add(`${images}/favicon.png`, await png(favicon("light"), 48));
for (const scheme of ["light", "dark"]) {
  for (const status of ["idle", "running", "attention"]) {
    const name = `favicon-${scheme}${status === "idle" ? "" : `-${status}`}`;
    const source = favicon(scheme, status);
    add(`${images}/${name}.svg`, source);
    add(`${images}/${name}.png`, await png(source, 48));
  }
}
for (const [name, size] of [
  ["apple-touch-icon", 180],
  ["pwa-icon-192", 192],
  ["pwa-icon-512", 512],
]) {
  add(
    `apps/mobile/public/${name}.png`,
    await png(name === "apple-touch-icon" ? mobile : maskable, size, true),
  );
}

// Refresh an existing iOS catalog explicitly; clean prebuilds consume app.config.js
// and the assets above automatically. Preserve Expo's asset filenames and metadata.
if (syncNative) {
  const ios = resolve(root, "apps/mobile/ios");
  let projects = [];
  try {
    projects = await readdir(ios, { withFileTypes: true });
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  for (const project of projects.filter((entry) => entry.isDirectory() && entry.name !== "Pods")) {
    const catalog = `apps/mobile/ios/${project.name}/Images.xcassets`;
    try {
      await access(resolve(root, catalog));
    } catch (error) {
      if (error.code === "ENOENT") continue;
      throw error;
    }
    add(`${catalog}/AppIcon.appiconset/App-Icon-1024x1024@1x.png`, await png(mobile, 1024, true));
    const contents = JSON.parse(
      await readFile(resolve(root, `${catalog}/SplashScreenLogo.imageset/Contents.json`)),
    );
    for (const scale of [1, 2, 3]) {
      for (const dark of [false, true]) {
        const existing = contents.images.find(
          (entry) =>
            entry.scale === `${scale}x` &&
            Boolean(entry.appearances?.some((appearance) => appearance.value === "dark")) === dark,
        );
        const filename =
          existing?.filename ?? `${dark ? "dark_" : ""}image${scale === 1 ? "" : `@${scale}x`}.png`;
        add(
          `${catalog}/SplashScreenLogo.imageset/${filename}`,
          await png(dark ? splashDark : splash, 200 * scale),
        );
        if (existing) {
          existing.filename = filename;
        } else {
          contents.images.push({
            filename,
            idiom: "universal",
            scale: `${scale}x`,
            ...(dark ? { appearances: [{ appearance: "luminosity", value: "dark" }] } : {}),
          });
        }
      }
    }
    add(
      `${catalog}/SplashScreenLogo.imageset/Contents.json`,
      `${JSON.stringify(contents, null, 2)}\n`,
    );
    const colorSet = JSON.parse(
      await readFile(resolve(root, `${catalog}/SplashScreenBackground.colorset/Contents.json`)),
    );
    for (const entry of colorSet.colors) {
      if (!entry.appearances?.some((appearance) => appearance.value === "dark")) {
        entry.color.components = {
          red: "0.980392",
          green: "0.980392",
          blue: "0.972549",
          alpha: "1.000000",
        };
      }
    }
    add(
      `${catalog}/SplashScreenBackground.colorset/Contents.json`,
      `${JSON.stringify(colorSet, null, 2)}\n`,
    );
  }
}

const stale = [];
for (const [path, expected] of outputs) {
  const absolute = resolve(root, path);
  if (check) {
    let actual;
    try {
      actual = await readFile(absolute);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (!actual?.equals(expected)) stale.push(path);
  } else {
    await mkdir(dirname(absolute), { recursive: true });
    await writeFile(absolute, expected);
  }
}
if (stale.length > 0) {
  console.error(`Stale brand assets; run npm run generate:icons:\n${stale.join("\n")}`);
  process.exitCode = 1;
} else {
  console.log(
    `${check ? "Verified" : "Generated"} ${outputs.size} AIT brand assets (${brand.version}).`,
  );
}
